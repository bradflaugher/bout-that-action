/**
 * Loudness trims (dB) per song, so every track the game plays sits in one tight loudness band
 * (BS.1770 integrated, at the default music volume, through the master bus). A song pinned to
 * one heat (title, themes, game over, sneak mixes) has one trim. A GUNS HOT arrangement has one
 * per point of [GRID] (calm, between, CAUTION, between, ALERT), followed linearly in between, so
 * the calm bed plays as full as the fight, the level climbs gently as heat builds, and a build
 * is density and brightness rather than a fader. A song with a trap drop
 * ([SongSpec.dropThreshold]) has three before the drop lands ([preDropGrid]: calm, halfway and
 * just under the threshold, so the bed holds its level as it builds) and three after it (the
 * upper half of [GRID]), so the drop arrives a step up, with its weight.
 *
 * GENERATED by `ATA_MUSIC_CALIBRATE=1 ./gradlew :app:testDebugUnitTest --tests '*MusicLevelsCalibration*'`
 * from renders of every song; rerun it after changing an arrangement, a patch or the mix.
 * [MusicQualityTest] fails when the music drifts out of the band.
 */
internal object MusicLevels {
    /** The heats a GUNS HOT arrangement's trims are measured at. */
    val GRID = floatArrayOf(0f, 0.25f, 0.5f, 0.75f, 0.95f)

    /** Where a drop song's first three trims are measured: calm, halfway, just under the drop. */
    fun preDropGrid(dropThreshold: Float) = floatArrayOf(0f, dropThreshold * 0.5f, dropThreshold - 0.02f)

    private val NONE = floatArrayOf(0f)

    fun of(name: String): FloatArray = overrides?.get(name) ?: TABLE[name] ?: NONE

    /** Trims to use instead of the table's (the calibration, between its passes). */
    @Volatile internal var overrides: Map<String, FloatArray>? = null

    /** Every song with a trim, for the calibration to start from. */
    internal val table: Map<String, FloatArray> get() = TABLE

    /**
     * The gain [trim] asks for at [heat]; for a drop song (six trims), [dropped] says whether its
     * drop has landed and [dropThreshold] where it lands. Allocation-free (the audio thread).
     */
    fun gainAt(trim: FloatArray, heat: Float, dropped: Boolean = true, dropThreshold: Float = -1f): Float {
        val h = heat.coerceIn(0f, 1f)
        val db = when (trim.size) {
            GRID.size -> along(trim, 0, GRID, 0, GRID.size, h)
            GRID.size + 1 -> if (dropped) {
                along(trim, 3, GRID, 2, 3, h)
            } else {
                // (Inline preDropGrid: no allocation.)
                val half = dropThreshold * 0.5f
                val top = dropThreshold - 0.02f
                if (h <= half) lerp(trim[0], trim[1], h / half) else lerp(trim[1], trim[2], (h - half) / (top - half))
            }
            else -> trim[0]
        }
        return 10f.pow(db / 20f)
    }

    /** Piecewise-linear [values] (from [vFrom]) over [count] points of [grid] (from [gFrom]), held flat past the ends. */
    private fun along(values: FloatArray, vFrom: Int, grid: FloatArray, gFrom: Int, count: Int, h: Float): Float {
        if (h <= grid[gFrom]) return values[vFrom]
        for (k in 1 until count) {
            val g0 = grid[gFrom + k - 1]
            val g1 = grid[gFrom + k]
            if (h <= g1) return lerp(values[vFrom + k - 1], values[vFrom + k], (h - g0) / (g1 - g0))
        }
        return values[vFrom + count - 1]
    }

    private fun lerp(a: Float, b: Float, t: Float) = a + (b - a) * t.coerceIn(0f, 1f)

